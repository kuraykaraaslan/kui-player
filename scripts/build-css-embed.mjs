#!/usr/bin/env node
// Builds the player CSS for the SHADOW-ROOT embed. Unlike scripts/build-css.mjs
// (which strips preflight so it won't clobber a host app), the embed lives inside
// a shadow root, so we KEEP preflight (safe, isolated resets) and re-target the
// design-token blocks from `:root` → `:host` so the custom properties actually
// resolve inside the shadow tree. Output is emitted as a TS string constant.
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");
const input = resolve(projectRoot, "src", "globals.css");
const output = resolve(projectRoot, "embed", "embed-css.generated.ts");

// FontAwesome's own base stylesheet (the one `config.autoAddCss` would inject) sizes the inline SVGs
// (`.svg-inline--fa { height: 1em; ... }`). We disable autoAddCss to avoid polluting the host page, so
// we must fold this CSS into the shadow-root stylesheet ourselves — otherwise icons render unsized.
const require = createRequire(import.meta.url);
const faCss = await readFile(require.resolve("@fortawesome/fontawesome-svg-core/styles.css"), "utf8");

const css = await readFile(input, "utf8");
const result = await postcss([tailwind()]).process(css, { from: input, to: output });

const root = postcss.parse(result.css);

// Mirror `:root` token rules onto `:host` (and `.dark` onto `:host(.dark)`) so
// the variables cascade inside the shadow root, then keep the originals too.
root.walkRules((rule) => {
  const selectors = rule.selectors;
  const mirror = [];
  for (const sel of selectors) {
    const trimmed = sel.trim();
    if (trimmed === ":root") mirror.push(":host");
    else if (trimmed === ".dark") mirror.push(":host(.dark)");
  }
  if (mirror.length > 0) {
    const clone = rule.clone();
    clone.selectors = mirror;
    rule.after(clone);
  }
});

const cssText = `${faCss}\n${root.toString()}`;
const banner =
  "// AUTO-GENERATED by scripts/build-css-embed.mjs — do not edit.\n" +
  "// Player stylesheet for the shadow-root embed.\n";
const file = `${banner}export const EMBED_CSS = ${JSON.stringify(cssText)};\n`;

await mkdir(dirname(output), { recursive: true });
await writeFile(output, file);
console.log(`[build-css-embed] ${output} (${cssText.length} bytes of CSS)`);
